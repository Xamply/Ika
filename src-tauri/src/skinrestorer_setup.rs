//! Installs and configures the SkinRestorer mod so that, on a server or an opened-to-LAN
//! world, everyone sees the skins published to the Ika skins service (device_key.rs).
//!
//! SkinRestorer (server side) looks each joining player up by name; we add the Ika
//! service as a "username-url" provider, first in the auto-fetch order (Mojang and Ely.by
//! still come after it). MineSkin, which SkinRestorer uses on its own, gets the skins
//! signed by Mojang so every client accepts them.

use serde_json::{json, Value};
use std::path::{Path, PathBuf};

const PROVIDER_NAME: &str = "ika";

/// SkinRestorer's own default config (format version 3, as generated by 2.11.0), used
/// when the server has none yet.
const DEFAULT_CONFIG: &str = r#"{
  "language": "en_us",
  "command": { "enabled": true, "permissionLevel": 0, "targetsPermissionLevel": 2 },
  "storage": { "location": "world" },
  "join": {
    "refreshSkin": true,
    "skipRefreshProviders": [],
    "applyDelay": 0,
    "autoFetch": { "enabled": true, "overrideExisting": false, "providers": ["mojang", "ely.by"] }
  },
  "request": { "proxy": "", "timeout": 10, "userAgent": "" },
  "providers": {
    "mojang": { "enabled": true, "name": "mojang", "cache": { "enabled": true, "duration": 60 } },
    "ely_by": { "enabled": true, "name": "ely.by", "cache": { "enabled": true, "duration": 60 } },
    "mineskin": { "apiKey": "", "proxyUrlUpload": false, "allowedDomains": [], "enabled": true, "name": "web", "cache": { "enabled": true, "duration": 300 } },
    "collection": { "sources": [], "enabled": false, "name": "collection", "cache": { "enabled": true, "duration": 604800 } },
    "custom": []
  },
  "version": 3
}"#;

/// Adds the Ika provider to config/skinrestorer/config.json under `root` (created from
/// the defaults if missing). Everything else in an existing config is kept.
pub fn merge_config(root: &Path, service: &str) -> Result<(), String> {
    let path = root.join("config").join("skinrestorer").join("config.json");
    let mut cfg: Value = std::fs::read_to_string(&path)
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or_else(|| serde_json::from_str(DEFAULT_CONFIG).expect("valid default config"));

    let provider = json!({
        "type": "username-url",
        "name": PROVIDER_NAME,
        "enabled": true,
        "urlTemplate": format!("{}/skins/{{username}}.png", service.trim_end_matches('/')),
        "cache": { "enabled": true, "duration": 300 }
    });
    let providers = cfg
        .as_object_mut()
        .ok_or("config.json de SkinRestorer inválido")?
        .entry("providers")
        .or_insert_with(|| json!({}));
    let custom = providers
        .as_object_mut()
        .ok_or("config.json: 'providers' inválido")?
        .entry("custom")
        .or_insert_with(|| json!([]));
    let list = custom.as_array_mut().ok_or("config.json: 'custom' inválido")?;
    list.retain(|p| p.get("name").and_then(|n| n.as_str()) != Some(PROVIDER_NAME));
    list.push(provider);

    let auto = cfg
        .pointer_mut("/join")
        .and_then(|j| j.as_object_mut())
        .map(|j| j.entry("autoFetch").or_insert_with(|| json!({ "enabled": true, "overrideExisting": false })))
        .ok_or("config.json: 'join' inválido")?;
    let auto = auto.as_object_mut().ok_or("config.json: 'autoFetch' inválido")?;
    auto.insert("enabled".to_string(), json!(true));
    let mut order: Vec<Value> = auto
        .get("providers")
        .and_then(|p| p.as_array())
        .cloned()
        .unwrap_or_else(|| vec![json!("mojang"), json!("ely.by")]);
    order.retain(|p| p.as_str() != Some(PROVIDER_NAME));
    order.insert(0, json!(PROVIDER_NAME));
    auto.insert("providers".to_string(), Value::Array(order));

    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    std::fs::write(&path, serde_json::to_string_pretty(&cfg).unwrap_or_default()).map_err(|e| e.to_string())
}

/// SkinRestorer jar for this Minecraft version and loader, from Modrinth (SHA-512 checked,
/// cached). Returns (file name, bytes).
pub fn skinrestorer_jar(agent: &ureq::Agent, mc_version: &str, loader: &str) -> Result<(String, Vec<u8>), String> {
    let q = |s: &str| format!("%5B%22{}%22%5D", s);
    let url = format!(
        "https://api.modrinth.com/v2/project/skinrestorer/version?game_versions={}&loaders={}",
        q(mc_version),
        q(loader)
    );
    let resp = agent.get(&url).call().map_err(|e| format!("Modrinth: {}", e))?;
    let versions: Value = serde_json::from_str(&resp.into_string().map_err(|e| e.to_string())?).map_err(|e| e.to_string())?;
    let file = versions
        .as_array()
        .and_then(|v| v.first())
        .and_then(|v| v.get("files").and_then(|f| f.as_array()))
        .and_then(|files| files.iter().find(|f| f.get("primary").and_then(|p| p.as_bool()) == Some(true)).or_else(|| files.first()))
        .ok_or_else(|| format!("SkinRestorer no está disponible para Minecraft {} con {} (necesita 1.19 o superior)", mc_version, loader))?;
    let name = file.get("filename").and_then(|v| v.as_str()).ok_or("Modrinth: archivo sin nombre")?.to_string();
    let dl = file.get("url").and_then(|v| v.as_str()).ok_or("Modrinth: archivo sin URL")?;
    let sha512 = file.pointer("/hashes/sha512").and_then(|v| v.as_str()).unwrap_or("").to_lowercase();

    let cache = crate::mc::ika_root().join("cache").join("skinrestorer").join(&name);
    let hash = |data: &[u8]| {
        use sha2::Digest;
        sha2::Sha512::digest(data).iter().map(|b| format!("{:02x}", b)).collect::<String>()
    };
    if let Ok(data) = std::fs::read(&cache) {
        if sha512.is_empty() || hash(&data) == sha512 {
            return Ok((name, data));
        }
    }
    let mut data = Vec::new();
    std::io::Read::read_to_end(&mut agent.get(dl).call().map_err(|e| format!("Modrinth: {}", e))?.into_reader(), &mut data)
        .map_err(|e| e.to_string())?;
    if !sha512.is_empty() && hash(&data) != sha512 {
        return Err("SkinRestorer: el checksum no coincide".to_string());
    }
    if let Some(parent) = cache.parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let _ = std::fs::write(&cache, &data);
    Ok((name, data))
}

pub fn has_skinrestorer(mods: &Path) -> Option<String> {
    std::fs::read_dir(mods).ok()?.flatten().find_map(|e| {
        let n = e.file_name().to_string_lossy().to_string();
        (n.to_lowercase().contains("skinrestorer") && n.to_lowercase().ends_with(".jar")).then_some(n)
    })
}

/// Installs SkinRestorer + the Ika config into a game/server folder (mods/ and config/).
/// Returns a short description of what was done.
pub fn install_into(agent: &ureq::Agent, root: &Path, mc_version: &str, loader: &str, service: &str) -> Result<String, String> {
    let mods = root.join("mods");
    std::fs::create_dir_all(&mods).map_err(|e| e.to_string())?;
    let jar_note = match has_skinrestorer(&mods) {
        Some(existing) => format!("SkinRestorer ya estaba instalado ({})", existing),
        None => {
            let (name, data) = skinrestorer_jar(agent, mc_version, loader)?;
            std::fs::write(mods.join(&name), data).map_err(|e| e.to_string())?;
            format!("SkinRestorer instalado ({})", name)
        }
    };
    merge_config(root, service)?;
    Ok(format!("{}, con las skins de Ika configuradas", jar_note))
}

/// Minecraft version written in a vanilla server jar (version.json, 1.14+).
fn jar_mc_version(jar: &Path) -> Option<String> {
    let file = std::fs::File::open(jar).ok()?;
    let mut zip = zip::ZipArchive::new(file).ok()?;
    let mut entry = zip.by_name("version.json").ok()?;
    let mut text = String::new();
    std::io::Read::read_to_string(&mut entry, &mut text).ok()?;
    let v: Value = serde_json::from_str(&text).ok()?;
    v.get("id").and_then(|i| i.as_str()).map(str::to_string)
}

fn first_subdir(dir: &Path) -> Option<String> {
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .ok()?
        .flatten()
        .filter(|e| e.path().is_dir())
        .map(|e| e.file_name().to_string_lossy().to_string())
        .collect();
    names.sort();
    names.pop()
}

/// (Minecraft version, loader) of a dedicated server folder.
pub fn detect_server(folder: &Path) -> Result<(String, String), String> {
    let libs = folder.join("libraries");
    let mc_from_libs = || first_subdir(&libs.join("net/minecraft/server")).map(|d| d.split('-').next().unwrap_or("").to_string());
    if libs.join("net/neoforged/neoforge").is_dir() {
        let mc = mc_from_libs().filter(|v| !v.is_empty()).ok_or("No se pudo leer la versión de Minecraft de este servidor NeoForge")?;
        return Ok((mc, "neoforge".to_string()));
    }
    if libs.join("net/minecraftforge/forge").is_dir() {
        let mc = first_subdir(&libs.join("net/minecraftforge/forge"))
            .and_then(|d| d.split('-').next().map(str::to_string))
            .or_else(mc_from_libs)
            .ok_or("No se pudo leer la versión de Minecraft de este servidor Forge")?;
        return Ok((mc, "forge".to_string()));
    }
    let loader = if folder.join("quilt-server-launch.jar").exists() || folder.join(".quilt").is_dir() {
        "quilt"
    } else if folder.join("fabric-server-launch.jar").exists()
        || folder.join("fabric-server-launcher.properties").exists()
        || folder.join(".fabric").is_dir()
    {
        "fabric"
    } else if folder.join("plugins").is_dir() {
        return Err("Es un servidor de plugins (Paper/Spigot): SkinRestorer es para servidores con Fabric, Quilt, Forge o NeoForge".to_string());
    } else {
        return Err("No parece la carpeta de un servidor con Fabric, Quilt, Forge o NeoForge".to_string());
    };
    // Vanilla server jar: the one named in fabric-server-launcher.properties, server.jar,
    // or any jar in the folder (and .fabric/server) that carries version.json.
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Ok(props) = std::fs::read_to_string(folder.join("fabric-server-launcher.properties")) {
        if let Some(j) = props.lines().find_map(|l| l.strip_prefix("serverJar=")) {
            candidates.push(folder.join(j.trim()));
        }
    }
    candidates.push(folder.join("server.jar"));
    for dir in [folder.to_path_buf(), folder.join(".fabric").join("server")] {
        if let Ok(rd) = std::fs::read_dir(&dir) {
            candidates.extend(rd.flatten().map(|e| e.path()).filter(|p| p.extension().map_or(false, |x| x == "jar")));
        }
    }
    let mc = candidates
        .iter()
        .find_map(|j| jar_mc_version(j))
        .ok_or("No se encontró el jar de Minecraft del servidor para saber su versión")?;
    Ok((mc, loader.to_string()))
}

/// Folder with mods/ + config/ ready to upload to a hosting panel.
pub fn export_for_hosting(agent: &ureq::Agent, mc_version: &str, loader: &str, service: &str) -> Result<PathBuf, String> {
    let out = crate::mc::ika_root().join("exports").join(format!("skins-{}-{}", loader, mc_version));
    let _ = std::fs::remove_dir_all(&out);
    install_into(agent, &out, mc_version, loader, service)?;
    let readme = format!(
        "Skins compartidas de Ika para tu servidor ({} {})\r\n\r\n\
         Sube estas carpetas a la raíz del servidor desde el panel del hosting:\r\n\
         - mods/  -> el mod SkinRestorer\r\n\
         - config/skinrestorer/config.json -> la configuración con las skins de Ika\r\n\r\n\
         Si tu servidor ya tenía SkinRestorer configurado, en vez de reemplazar su config.json\r\n\
         añade el proveedor \"ika\" de este archivo a la lista providers.custom y pon \"ika\"\r\n\
         primero en join.autoFetch.providers.\r\n\r\n\
         Después reinicia el servidor.\r\n",
        loader, mc_version
    );
    let _ = std::fs::write(out.join("LEEME.txt"), readme);
    Ok(out)
}
