"""Pack the reference sprites and two repeating sRGB gradients into one GPU atlas."""

from bisect import bisect_right
import json
from pathlib import Path

from PIL import Image

root = Path(__file__).resolve().parent.parent
scratch = root / "scratch/titlebar-reference"
assets = root / "src/titlebar"
assets.mkdir(exist_ok=True)
layout = json.loads((scratch / "layout.json").read_text())
source = Image.open(scratch / "sprites.png").convert("RGBA")
assert source.width == 600
rects = layout["rects"]

# Ordinary masks use alpha. Pack the monitor text in red over the same
# rows, below the RGBA logo; it doesn't need its own page or texture.
primary_bottom = max(y + h for key, (_, y, _, h) in rects.items()
                     if not key.startswith(("monitor", "digit", "bold")))
left, y, row = 1, 36, 0
monitor_masks = []
for key, (old_x, old_y, w, h) in rects.items():
    if not key.startswith(("monitor", "digit", "bold")):
        continue
    if left + w > 299:
        left, y, row = 1, y + row + 2, 0
    rects[key] = [left, y, w, h]
    monitor_masks.append((source.crop((old_x*2, old_y*2, (old_x+w)*2, (old_y+h)*2)).getchannel("A"),
                          (left*2, y*2)))
    left += w + 2
    row = max(row, h)

atlas = source.crop((0, 0, 600, 2 * (max(primary_bottom, y + row) + 1)))
red, green, blue, alpha = atlas.split()
red.paste(0, (0, 72, atlas.width, atlas.height))
for mask, point in monitor_masks:
    red.paste(mask, point)
atlas = Image.merge("RGBA", (red, green, blue, alpha))

# Four rows per gradient, one sample per SVG unit. The shader interpolates
# across rows/the period boundary in sRGB, just like the SVG gradient.
for j, stops in enumerate(json.loads((scratch / "gradients.json").read_text())):
    offsets = [t for t, _ in stops]
    colors = [bytes.fromhex(hex_rgb) for _, hex_rgb in stops]
    assert offsets[0] == 0
    if offsets[-1] < 1:
        offsets.append(1.0)  # SVG extends its last stop to the end of its period.
        colors.append(colors[-1])
    for i in range(2400):
        pos = i / 2400
        k = bisect_right(offsets, pos)
        f = (pos - offsets[k - 1]) / (offsets[k] - offsets[k - 1])
        rgba = tuple(round(a + (b - a) * f) for a, b in zip(colors[k - 1], colors[k])) + (255,)
        atlas.putpixel((i % 600, j * 4 + i // 600), rgba)
atlas.save(assets / "atlas.png", optimize=True)

def vec(numbers):
    return "vec4(" + ", ".join(str(float(n)) for n in numbers) + ")"

def array(name, rects):
    return "const " + name + " = array(" + ", ".join(vec(rect) for rect in rects) + ");\n"

wgsl = "// Generated by tools/pack_titlebar.py. Sprite rectangles are in CSS pixels (2x atlas).\n"
for name in ("logo", "name"):
    wgsl += "const " + name.upper() + "_SPRITE = " + vec(rects[name]) + ";\n"
wgsl += array("CONTROL_SPRITES", [rects[name] for name in ("minimize", "maximize", "close", "notify")])
wgsl += array("TAB_TEXT", [rects[f"text{i}_{j}"] for i in range(5) for j in range(2)])
wgsl += array("TAB_ICONS", [rects["plate0" if i == 3 else f"icon{i}"] for i in range(5)])
wgsl += array("MANAGER_PLATES", [rects[f"plate{i}"] for i in range(4)])
wgsl += array("NOTIFICATION_SPRITES", [rects[f"notify{part}"] for part in ("Title", "Read", "Clear", "EmptyIcon", "Empty")])
wgsl += array("MONITOR_SPRITES", [rects[f"monitor{part}"] for part in ("Title", "Intro", "Label", "Times", "Scale", "Percent", "Primary", "Current", "Empty", "Error")])
wgsl += array("MONITOR_DIGITS", [rects[f"{style}{i}"] for style in ("digit", "bold") for i in range(10)])
(assets / "atlas.wgsl").write_text(wgsl, encoding="utf-8")
rust = "// Generated by tools/pack_titlebar.py from the reference's DOM layout.\n"
rust += f"pub const TAB_WIDTHS: [[f32; 5]; 2] = {layout['widths']!r};\n"
(assets / "layout.rs").write_text(rust, encoding="utf-8")
