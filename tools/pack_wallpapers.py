"""Build the tiny glyphs, labels and bundled posters for the Wallpapers window."""

import os
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageOps

ROOT = Path(__file__).resolve().parent.parent
WORKSHOP = ROOT / 'media'
FONT_DIR = Path(os.environ.get('WINDIR', 'C:/Windows')) / 'Fonts'

LABELS = {
    'title': ('WALLPAPERS', 13), 'downloaded': ('Fondos Descargados', 13),
    'steam': ('Wallpaper Engine', 13), 'motion': ('MotionBGs', 13),
    'playlist': ('Playlist de Fondo', 13), 'current': ('Fondo activo:', 12),
    'search': ('Buscar en tus fondos descargados…', 13),
    'search_steam': ('Buscar entre las escenas instaladas…', 13),
    'local': ('Instalados en tu PC', 12), 'online': ('Catálogo Online (Steam Community)', 12),
    'open_motion': ('Abrir catálogo MotionBGs ↗', 13),
    'motion_hint': ('Consulta el catálogo en tu navegador.', 14),
    'no_results': ('No hay fondos en esta vista', 16),
    'empty_list': ('Tu playlist de fondos está vacía', 16),
    'list_hint': ('Añade fondos con + desde la pestaña Fondos Descargados.', 13),
    'on': ('PLAYLIST ACTIVADA', 12), 'off': ('PLAYLIST DESACTIVADA', 12),
    'duration': ('Duración:', 12), 'add': ('+ Agregar fondo actual', 12),
    'clear': ('Vaciar playlist', 12), 'active': ('Activo', 11), 'scene': ('ESCENA', 10),
    'video': ('MP4', 10), 'settings': ('Ajustes de Fondo', 14), 'dim': ('Oscurecer fondo', 13),
    'switching': ('Cambiando fondo…', 12),
    'badge_steam': ('STEAM', 10), 'badge_motion': ('MOTIONBGS', 10),
    'badge_imported': ('IMPORTADO', 10), 'badge_mb': ('MB', 10),
    'badge_4k': ('4K', 9), 'badge_1440p': ('1440p', 9), 'badge_1080p': ('1080p', 9),
    'filter_all': ('Todos', 12), 'filter_steam': ('Wallpaper Engine (Steam)', 12),
    'filter_motion': ('MotionBGs', 12), 'filter_imported': ('Importados', 12),
    'filter_ready': ('fondos listos en tu PC', 12),
}


def populate(add):
    def font(size, bold=True):
        return ImageFont.truetype(str(FONT_DIR / ('segoeuib.ttf' if bold else 'segoeui.ttf')), size)

    for name, (label, size) in LABELS.items():
        f = font(size, name not in ('search', 'search_steam', 'motion_hint', 'list_hint'))
        tracking = {'scene': .6, 'badge_steam': .8, 'badge_motion': .8, 'badge_imported': .8}.get(name)
        if tracking is not None:
            f = ImageFont.truetype(str(FONT_DIR / 'seguibl.ttf'), size)
            im = Image.new('RGBA', (round(f.getlength(label) + len(label) * tracking) + 6, 25))
            draw = ImageDraw.Draw(im)
            for i, char in enumerate(label):
                draw.text((2 + f.getlength(label[:i]) + i * tracking, 20),
                          char, font=f, fill='white', anchor='ls')
            add(f'wp_{name}', im, (0, 0))
            continue
        im = Image.new('RGBA', (round(f.getlength(label)) + 4, 25))
        ImageDraw.Draw(im).text((2, 20), label, font=f, fill='white', anchor='ls')
        add(f'wp_{name}', im, (0, 0))

    glyphs = Image.new('RGBA', (16 * 12, 14 * 18))
    draw = ImageDraw.Draw(glyphs)
    f = font(13)
    for code in range(32, 256):
        i = code - 32
        draw.text((i % 16 * 12 + 1, i // 16 * 18 + 13), chr(code), font=f,
                  fill='white', anchor='ls')
    add('wp_glyphs', glyphs, (0, 0), trim=False)
    widths = [str(max(3, round(f.getlength(chr(code))))) for code in range(32, 256)]
    rows = '\n'.join('    ' + ', '.join(widths[i:i + 16]) + ',' for i in range(0, 224, 16))
    (ROOT / 'src/dock/wall_glyphs.rs').write_text(
        '// Generated by tools/pack_wallpapers.py.\npub const ADVANCE: [u8; 224] = [\n' + rows + '\n];\n',
        encoding='utf-8')

    for i, id in enumerate(('3608457742', '3635457818', '3003524837'), 1):
        with Image.open(WORKSHOP / id / 'preview.gif') as source:
            source.seek(min(source.n_frames - 1, 8))
            poster = ImageOps.fit(source.convert('RGB'), (232, 160), Image.Resampling.LANCZOS)
        add(f'wp_poster{i}', poster.convert('RGBA'), (0, 0))
