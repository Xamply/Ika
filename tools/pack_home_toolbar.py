"""Rasterize the native Home toolbar's Segoe UI labels as grayscale masks."""

import os
from math import ceil
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


OUT = Path(__file__).resolve().parent.parent / "src" / "home"
FONT_DIR = Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts"
SCALE = 2
PADDING = 2
FONTS = {
    weight: ImageFont.truetype(str(FONT_DIR / file), 14 * SCALE)
    for weight, file in [(600, "seguisb.ttf"), (700, "segoeuib.ttf")]
}
LABELS = [
    ("Crear Instancia", (700,)),
    ("Todas", (600, 700)),
    ("Recientes", (600, 700)),
    ("Favoritas", (600, 700)),
    ("Buscar instancia...", (600,)),
]


def main():
    bounds = [FONTS[weight].getbbox(text, anchor="ls")
              for text, weights in LABELS for weight in weights]
    top, bottom = min(rect[1] for rect in bounds), max(rect[3] for rect in bounds)
    height = bottom - top + 2 * PADDING
    cells = [(text, weights, ceil(max(FONTS[w].getlength(text) for w in weights)) + 2 * PADDING)
             for text, weights in LABELS]
    mask = Image.new("L", (sum(width * len(weights) for _, weights, width in cells), height))
    draw = ImageDraw.Draw(mask)
    x = 0
    rects = []
    for text, weights, width in cells:
        # Both weights use the same slot width and baseline to keep icons fixed.
        for weight in weights:
            font = FONTS[weight]
            left = x + (width - font.getlength(text)) / 2
            draw.text((left, PADDING - top), text, font=font, fill=255, anchor="ls")
            rects.append(f"    vec4({x}.0, 0.0, {width}.0, {height}.0), // {text} {weight}")
            x += width
    atlas = Image.new("RGBA", mask.size, "white")
    atlas.putalpha(mask)
    atlas.save(OUT / "toolbar_labels.png", optimize=True)
    (OUT / "toolbar_labels.wgsl").write_text(
        "// Generated by tools/pack_home_toolbar.py.\n"
        f"const HOME_LABEL_RASTER_SCALE = {SCALE}.0;\n"
        f"const HOME_LABEL_STRIP_HEIGHT = {height}.0;\n"
        "const HOME_TOOLBAR_LABELS = array(\n" + "\n".join(rects) + "\n);\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
